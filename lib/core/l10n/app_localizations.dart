/// Lightweight, dependency-free localization layer.
///
/// This backs REQ-change-language: the Language screen commits the chosen code
/// to [AppState], which notifies the tree; every widget that reads a string via
/// `context.l10n` rebuilds and pulls the translation for the new code, so the UI
/// re-localizes app-wide with no restart. Missing translations fall back to the
/// English base (and, ultimately, to the raw key) so a partially-translated
/// locale still renders sensibly.
///
/// The catalogue covers the strings surfaced by the language-change flow
/// (Settings + Language screens). Screens read it through the [BuildContext]
/// extensions below; long-form legal bodies stay in their host widgets.
class L10n {
  const L10n(this.code);

  /// The active language code (a [LanguageOption.code], e.g. `fr`, `zh-Hant`).
  final String code;

  /// Translate [key] for the active language, falling back to English then to
  /// [fallback] (or the key itself) when no entry exists.
  String t(String key, [String? fallback]) {
    final byLang = _kStrings[key];
    if (byLang == null) return fallback ?? key;
    return byLang[code] ?? byLang[kDefaultLanguageCode] ?? fallback ?? key;
  }
}

/// Ergonomic access to the active [L10n] from a [BuildContext].
extension L10nX on BuildContext {
  /// Rebuilds this widget when the language changes (use inside `build`).
  L10n get l10n => L10n(AppScope.of(this).languageCode);

  /// Read-only lookup for use inside callbacks (no dependency registered).
  L10n get l10nRead => L10n(AppScope.read(this).languageCode);
}

